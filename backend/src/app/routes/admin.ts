// Agrupa operações administrativas; autenticação de admin e limite de escrita são aplicados a todas.
import * as resources from "../controllers/adminResourcesController.ts";
import * as identity from "../controllers/identityController.ts";
import { updateRentalStatus } from "../controllers/rentalsController.ts";
import { updateAdminItem, archiveAdminItem, unarchiveAdminItem } from "../controllers/adminItemsController.ts";
import { adminWriteLimit } from "../middlewares/adminWriteLimit.ts";
import { Router } from "express";
import { correctUserCpf, deleteUser, getAdminUserSubscription, getUser, listAdminItems, listAdminRentals, listUsers, metrics, updateUserStatus } from "../controllers/adminController.ts";
import { requireAdmin } from "../middlewares/auth.ts";
import * as occurrences from "../controllers/adminOccurrencesController.ts";
import * as adminNotifications from "../controllers/adminNotificationsController.ts";
import * as campaigns from "../controllers/adminCampaignsController.ts";
import { listAudit } from "../controllers/adminAuditController.ts";
import { validate } from "../middlewares/validate.ts";
import { idParamsSchema } from "../schemas/common.ts";
import { adminCampaignSchema, adminCampaignTestSchema, adminCategoryMoveSchema, adminCategorySchema, adminCpfSchema, adminIdentityDecisionSchema, adminItemSchema, adminMarkAllSchema, adminNotificationPreferencesSchema, adminNotificationReadSchema, adminOccurrenceReplySchema, adminOccurrenceStatusSchema, adminReasonSchema, adminReviewSchema, adminStatusSchema, adminUnarchiveSchema } from "../schemas/admin.schema.ts";
const router = Router();
router.use(requireAdmin);
router.use(adminWriteLimit);
router.get("/metricas", metrics);
router.get("/auditoria", listAudit);
router.get("/ocorrencias/resumo", occurrences.occurrenceSummary);
router.get("/ocorrencias", occurrences.listOccurrences);
router.get("/ocorrencias/:id", validate({params:idParamsSchema}), occurrences.getOccurrence);
router.patch("/ocorrencias/:id/status", validate({params:idParamsSchema,body:adminOccurrenceStatusSchema}), occurrences.updateOccurrenceStatus);
router.post("/ocorrencias/:id/resposta", validate({params:idParamsSchema,body:adminOccurrenceReplySchema}), occurrences.replyOccurrence);
// Caminhos estáticos precedem /:id para não serem capturados como UUID.
router.get("/notificacoes/resumo", adminNotifications.adminNotificationSummary);
router.get("/notificacoes/preferencias", adminNotifications.getAdminNotificationPreferences);
router.put("/notificacoes/preferencias", validate({body:adminNotificationPreferencesSchema}), adminNotifications.putAdminNotificationPreferences);
router.post("/notificacoes/marcar-todas", validate({body:adminMarkAllSchema}), adminNotifications.markAllAdminNotifications);
router.get("/notificacoes", adminNotifications.listAdminNotifications);
router.patch("/notificacoes/:id", validate({params:idParamsSchema,body:adminNotificationReadSchema}), adminNotifications.markAdminNotification);
router.post("/notificacoes/:id/dispensar", validate({params:idParamsSchema}), adminNotifications.dismissAdminNotification);
router.get("/comunicados/estatisticas", campaigns.campaignStats);
router.get("/comunicados/destinatarios/contagem", campaigns.audienceCount);
router.post("/comunicados/teste", validate({body:adminCampaignTestSchema}), campaigns.testCampaign);
router.get("/comunicados", campaigns.listCampaigns);
router.post("/comunicados", validate({body:adminCampaignSchema}), campaigns.createCampaign);
router.put("/comunicados/:id", validate({params:idParamsSchema,body:adminCampaignSchema}), campaigns.updateCampaign);
router.delete("/comunicados/:id", validate({params:idParamsSchema}), campaigns.deleteCampaign);
router.get("/usuarios", listUsers);
router.get("/usuarios/:id/assinatura", validate({params:idParamsSchema}), getAdminUserSubscription);
router.get("/usuarios/:id/alugueis", validate({params:idParamsSchema}), listAdminRentals);
router.get("/usuarios/:id", validate({params:idParamsSchema}), getUser);
router.patch("/usuarios/:id/cpf", validate({params:idParamsSchema,body:adminCpfSchema}), correctUserCpf);
router.patch("/usuarios/:id/status", validate({params:idParamsSchema,body:adminStatusSchema}), updateUserStatus);
router.delete("/usuarios/:id", validate({params:idParamsSchema}), deleteUser);
router.get("/objetos", listAdminItems);
router.get("/alugueis", listAdminRentals);
router.patch("/objetos/:id", validate({params:idParamsSchema,body:adminItemSchema}), updateAdminItem);
router.delete("/objetos/:id", validate({params:idParamsSchema}), archiveAdminItem);
router.post("/objetos/:id/desarquivar", validate({params:idParamsSchema,body:adminUnarchiveSchema}), unarchiveAdminItem);
router.patch("/alugueis/:id", validate({params:idParamsSchema}), updateRentalStatus);
router.get("/conciliacoes",resources.adminReconciliations);
router.get("/conciliacoes/:id", validate({params:idParamsSchema}), resources.adminReconciliation);
router.post("/conciliacoes/:id/ignorar", validate({params:idParamsSchema}), resources.ignoreReconciliation);
router.get("/webhooks-pendentes",resources.adminPendingWebhooks);
router.get("/pagamentos", resources.adminPayments);
router.get("/pagamentos/estatisticas", resources.adminPaymentStats);
router.get("/pagamentos/:id", validate({params:idParamsSchema}), resources.adminPayment);
router.post("/pagamentos/:id/estornar", (_req,res)=>res.status(410).json({success:false,codigo:"operacao_descontinuada",message:"O painel não realiza estornos de aluguéis. Pagamentos de planos exigem tratamento no provedor e conciliação."}));
router.get("/verificacoes", identity.listIdentities);
router.get("/verificacoes/:id", validate({params:idParamsSchema}), identity.getIdentity);
router.patch("/verificacoes/:id", validate({params:idParamsSchema,body:adminIdentityDecisionSchema}), identity.reviewIdentity);
router.get("/verificacoes/:id/documentos/:tipo", validate({params:idParamsSchema}), identity.identityDocument);
router.get("/verificacoes/:id/arquivos/:tipo", validate({params:idParamsSchema}), identity.identityDocument);
router.get("/suporte", resources.listCases("suporte"));
router.patch("/suporte/:id", validate({params:idParamsSchema}), resources.reviewCase("suporte"));
router.get("/denuncias", resources.listCases("denuncia"));
router.patch("/denuncias/:id", validate({params:idParamsSchema}), resources.reviewCase("denuncia"));
router.get("/sinistros", resources.listCases("sinistro"));
router.patch("/sinistros/:id", validate({params:idParamsSchema}), resources.reviewCase("sinistro"));
router.get("/avaliacoes", resources.adminReviews);
router.patch("/avaliacoes/:id", validate({params:idParamsSchema,body:adminReviewSchema}), resources.updateReview);
router.delete("/avaliacoes/:id", validate({params:idParamsSchema,body:adminReasonSchema}), resources.removeReview);
router.get("/categorias", resources.listAdminCategories);
router.post("/categorias", validate({body:adminCategorySchema}), resources.saveCategory);
router.patch("/categorias/:id", validate({params:idParamsSchema,body:adminCategorySchema}), resources.saveCategory);
router.post("/categorias/:id/mover-itens", validate({params:idParamsSchema,body:adminCategoryMoveSchema}), resources.moveCategoryItems);
router.delete("/categorias/:id", validate({params:idParamsSchema}), resources.deleteCategory);
export default router;

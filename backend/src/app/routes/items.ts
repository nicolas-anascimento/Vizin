// Expõe catálogo público e operações de anúncio; uploads passam por validação de imagem.
import { verifyUploads } from "../middlewares/privateUpload.ts";
import { Router } from "express";
import { itemAvailability, createItem, deleteItem, getItem, listCategories, listItems, myItems, requireMutableOwnedItem, updateItem } from "../controllers/itemsController.ts";
import { requireAuth } from "../middlewares/auth.ts";
import { createItemUpload, updateItemUpload } from "../middlewares/upload.ts";
import { listItemReviews } from "../controllers/reviewsController.ts";
import { validate } from "../middlewares/validate.ts";
import { idParamsSchema } from "../schemas/common.ts";
import { listItemsQuerySchema } from "../schemas/objects.schema.ts";
const router = Router();
router.get("/categorias", listCategories);
router.get("/meus", requireAuth, myItems);
router.get("/", validate({ query: listItemsQuerySchema }), listItems);
router.get("/:id/disponibilidade", validate({ params: idParamsSchema }), itemAvailability);
router.get("/:id/avaliacoes", validate({ params: idParamsSchema }), listItemReviews);
router.get("/:id", validate({ params: idParamsSchema }), getItem);
router.post("/", requireAuth, createItemUpload, verifyUploads, createItem);
router.put("/:id", requireAuth, validate({ params: idParamsSchema }), requireMutableOwnedItem, updateItemUpload, verifyUploads, updateItem);
router.patch("/:id", requireAuth, validate({ params: idParamsSchema }), requireMutableOwnedItem, updateItemUpload, verifyUploads, updateItem);
router.delete("/:id", requireAuth, validate({ params: idParamsSchema }), deleteItem);
export default router;

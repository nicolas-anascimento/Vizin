// Expõe ciclo da solicitação: criação, status, pagamento, fotos, multa, relato e avaliação.
import { createReview, listRentalReviews } from "../controllers/reviewsController.ts";
import { rateLimit } from "../middlewares/rateLimit.ts";
import { Router } from "express";
import { createRentalRequest, getRentalStatus, listMyRentals, updateRentalStatus, cancelRentalRequest } from "../controllers/rentalsController.ts";
import { releaseDemoWithdrawal } from "../controllers/handoverController.ts";
import { recordHandover, handoverStatus } from "../controllers/handoverController.ts";
import { withdrawalUpload } from "../middlewares/upload.ts";
import { verifyUploads } from "../middlewares/privateUpload.ts";
import { listRentalReports } from "../controllers/rentalReportsController.ts";
import { requireAuth } from "../middlewares/auth.ts";
import { validate } from "../middlewares/validate.ts";
import { idParamsSchema } from "../schemas/common.ts";
import { createRentalSchema, handoverBodySchema, rentalListQuerySchema, rentalStatusSchema } from "../schemas/rentals.schema.ts";
import { reviewBodySchema } from "../schemas/reviews.schema.ts";
const router = Router();
const financialRouteRemoved: import("express").RequestHandler = (_req, res) => res.status(410).json({ success: false, codigo: "rota_financeira_descontinuada", message: "O VIZIN não processa pagamentos de aluguel ou multas. Combine o pagamento diretamente com a outra parte." });
router.use(requireAuth);
router.get("/", validate({ query: rentalListQuerySchema }), listMyRentals);
router.post("/", validate({ body: createRentalSchema }), createRentalRequest);
router.get("/historico", validate({ query: rentalListQuerySchema }), listMyRentals);
router.post("/:id/cancelamento", validate({ params: idParamsSchema }), cancelRentalRequest);
router.get("/:id/relatos", validate({ params: idParamsSchema }), listRentalReports);
router.get("/:id/retirada", validate({ params: idParamsSchema }), handoverStatus(false));
router.post("/:id/retirada/demo", rateLimit({windowMs:60000,max:10}), releaseDemoWithdrawal);
// O upload valida as fotos antes de chegar ao controller que confirma a etapa no banco.
router.post("/:id/retirada/fotos", validate({ params: idParamsSchema }), withdrawalUpload, verifyUploads, validate({body:handoverBodySchema}), recordHandover(false));
router.get("/:id/devolucao", validate({ params: idParamsSchema }), handoverStatus(true));
router.post("/:id/devolucao/fotos", validate({ params: idParamsSchema }), withdrawalUpload, verifyUploads, validate({body:handoverBodySchema}), recordHandover(true));
router.patch("/:id", validate({ params: idParamsSchema, body: rentalStatusSchema }), updateRentalStatus);
router.post("/:id/avaliacao", validate({ params: idParamsSchema, body: reviewBodySchema }), createReview);
router.get("/:id/avaliacoes", validate({ params: idParamsSchema }), listRentalReviews);
router.get("/:id/status", validate({ params: idParamsSchema }), getRentalStatus);
router.get("/:id/pagamento", financialRouteRemoved);
router.get("/:id/confirmacao-pagamento", financialRouteRemoved);
router.post("/:id/pagamentos", financialRouteRemoved);
router.post("/:id/pagamentos/demo", financialRouteRemoved);
router.get("/:id/multa", financialRouteRemoved);
router.post("/:id/multa/pagamentos", financialRouteRemoved);
router.post("/:id/multa/pagamentos/demo", financialRouteRemoved);
router.get("/:id", validate({ params: idParamsSchema }), getRentalStatus);
router.patch("/:id/status", validate({ params: idParamsSchema, body: rentalStatusSchema }), updateRentalStatus);
export default router;

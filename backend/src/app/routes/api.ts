// Compõe a API: rotas públicas, rotas autenticadas, administração e aliases de contratos antigos.
import * as addresses from "../controllers/addressesController.ts";
import conversations from "./conversations.ts";
import * as support from "../controllers/supportController.ts";
import * as chat from "../controllers/conversationsController.ts";
import { attachmentUpload, verifyChatAttachment } from "../middlewares/privateUpload.ts";
import { rateLimit } from "../middlewares/rateLimit.ts";
import { Router } from "express";
import login from "./login.ts";
import accounts from "./accounts.ts";
import users from "./users.ts";
import items from "./items.ts";
import rentals from "./rentals.ts";
import cards from "./cards.ts";
import payments from "./payments.ts";
import notifications from "./notifications.ts";
import { handoverRouter } from "./withdrawals.ts";
import withdrawals from "./withdrawals.ts";
import reviews from "./reviews.ts";
import messages from "./messages.ts";
import admin from "./admin.ts";
import { listCategories } from "../controllers/itemsController.ts";
import { requireAuth } from "../middlewares/auth.ts";
import { createRentalReport } from "../controllers/rentalReportsController.ts";
import { listItemReviews } from "../controllers/reviewsController.ts";
import subscriptions from "./subscriptions.ts";
import { validate } from "../middlewares/validate.ts";
import { idParamsSchema } from "../schemas/common.ts";
import { userIdParamsSchema } from "../schemas/conversations.schema.ts";
import { helpBodySchema, reportBodySchema, claimBodySchema } from "../schemas/support.schema.ts";
import { addressPatchSchema } from "../schemas/addresses.schema.ts";

const router = Router();
router.use(subscriptions);
router.get("/saude", (_req, res) => res.json({ status: "ok", servico: "vizin-api" }));
// Compatibilidade com clientes antigos: simulação de cobrança de aluguel fica
// sempre desativada. Assinaturas dependem do provedor real e de webhook.
router.get("/configuracao-publica", (_req, res) => res.json({ pagamentos_demo: false, cobranca_ativa: "assinaturas" }));
router.use("/login", login);
router.use("/contas", accounts);
router.use("/usuarios", users);
router.get("/enderecos", requireAuth, addresses.listAddresses);
router.get("/enderecos/:id", requireAuth, validate({params:idParamsSchema}), addresses.getAddress);
router.post("/enderecos", requireAuth, validate({body:addressPatchSchema}), addresses.saveAddress);
router.patch("/enderecos/:id", requireAuth, validate({params:idParamsSchema,body:addressPatchSchema}), addresses.saveAddress);
router.put("/enderecos/:id", requireAuth, validate({params:idParamsSchema,body:addressPatchSchema}), addresses.saveAddress);
router.delete("/enderecos/:id", requireAuth, validate({params:idParamsSchema}), addresses.removeAddress);
router.use("/objetos", items);
router.get("/produtos/:id/avaliacoes", validate({params:idParamsSchema}), listItemReviews);
router.get("/categorias", listCategories);
// Solicitações e aluguéis compartilham o mesmo router; os dois caminhos são aliases da API.
router.use("/solicitacoes", rentals);
router.use("/alugueis", rentals);
// O webhook é registrado em app.ts antes do parser JSON; aqui ficam as demais rotas financeiras.
router.use("/pagamentos", payments);
router.use("/cartoes", cards);
router.get("/pedidos/:id", requireAuth, (_req,res)=>res.status(410).json({success:false,codigo:"rota_financeira_descontinuada",message:"Consulta financeira de aluguel descontinuada."}));
router.use("/notificacoes", notifications);
router.use("/retiradas", withdrawals);
router.use("/devolucoes", handoverRouter(true));
router.use("/avaliacoes", reviews);
router.use("/mensagens", messages);
router.use("/conversations", conversations);
router.post("/users/:userId/block", requireAuth, validate({params:userIdParamsSchema}), chat.blockUser);
router.post("/users/:userId/unblock", requireAuth, validate({params:userIdParamsSchema}), chat.unblockUser);
router.get("/blocked-users", requireAuth, chat.blockedUsers);
router.post("/uploads", requireAuth, rateLimit({windowMs:60000,max:20}), attachmentUpload, verifyChatAttachment, chat.uploadAttachment);
router.get("/uploads/:id", requireAuth, validate({params:idParamsSchema}), chat.downloadAttachment);
router.post("/suporte/ajuda", requireAuth, rateLimit({windowMs:60000,max:5}), validate({body:helpBodySchema}), support.requestHelp);
router.post("/suporte/denuncia", requireAuth, rateLimit({windowMs:60000,max:5}), validate({body:reportBodySchema}), support.report);
router.post("/suporte/sinistro", requireAuth, validate({body:claimBodySchema}), support.reportClaim);
router.get("/suporte/me", requireAuth, support.mySupport);
router.post("/relatos", requireAuth, rateLimit({windowMs:60000,max:5}), createRentalReport);
router.use("/admin", admin);
export default router;

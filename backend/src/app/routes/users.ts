// Expõe cadastro, perfil, identidade, endereço e preferências; rotas privadas exigem sessão.
import * as settings from "../controllers/accountSettingsController.ts";
import * as addresses from "../controllers/addressesController.ts";
import * as identity from "../controllers/identityController.ts";
import { identityUpload } from "../middlewares/privateUpload.ts";
import { verifyUploads } from "../middlewares/privateUpload.ts";
import { Router } from "express";
import { addressPatchSchema } from "../schemas/addresses.schema.ts";
import { register } from "../controllers/authController.ts";
import { ownProfile, publicProfile, updateProfile, uploadAvatar } from "../controllers/usersController.ts";
import { requireAuth } from "../middlewares/auth.ts";
import { avatarUpload } from "../middlewares/upload.ts";
import { rateLimit } from "../middlewares/rateLimit.ts";
import { getMyRentalBlock } from "../controllers/rentalsController.ts";
import { confirmEmailAddress, resendEmailVerification } from "../controllers/emailVerificationController.ts";
import { validate } from "../middlewares/validate.ts";
import { registerSchema } from "../schemas/auth.schema.ts";
import { changeEmailSchema, changePhoneSchema, changePasswordSchema, notificationPreferencesPatchSchema, profilePatchSchema, privacySchema } from "../schemas/users.schema.ts";
import { idParamsSchema, tokenSchema } from "../schemas/common.ts";
import { listReceivedReviews } from "../controllers/reviewsController.ts";
const router = Router();
router.post("/", rateLimit({ windowMs: 60 * 60_000, max: 10, identity: "ip", scope: "register" }), validate({ body: registerSchema }), register);
router.post("/email/verificar", rateLimit({ windowMs: 15 * 60_000, max: 20, identity: "ip", scope: "email-confirm" }), confirmEmailAddress);
router.post("/email/reenviar", requireAuth, rateLimit({ windowMs: 60 * 60_000, max: 3, scope: "email-resend" }), resendEmailVerification);
router.get("/me", requireAuth, ownProfile);
router.get("/me/bloqueio", requireAuth, getMyRentalBlock);
router.patch("/me", requireAuth, validate({ body: profilePatchSchema }), updateProfile);
router.get("/perfil", requireAuth, ownProfile);
router.put("/perfil", requireAuth, validate({ body: profilePatchSchema }), updateProfile);
router.patch("/perfil", requireAuth, validate({ body: profilePatchSchema }), updateProfile);
router.post("/avatar", requireAuth, avatarUpload, verifyUploads, uploadAvatar);
router.delete("/avatar", requireAuth, settings.deleteAvatar);
router.post("/me/desativar", requireAuth, settings.deactivateAccount);
router.delete("/me", requireAuth, settings.closeAccount);
router.get("/me/exportar", requireAuth, settings.exportAccount);
router.put("/senha", requireAuth, validate({ body: changePasswordSchema }), settings.changePassword);
router.put("/telefone", requireAuth, validate({ body: changePhoneSchema }), settings.changePhone);
router.put("/email", requireAuth, validate({ body: changeEmailSchema }), settings.changeEmail);
router.get("/email/confirmar", (req, res) => {
  const token = req.query.token;
  res.setHeader("Cache-Control", "no-store");
  res.setHeader("Referrer-Policy", "no-referrer");
  const parsed = tokenSchema.safeParse(token);
  const query = parsed.success
    ? `?tipo=alteracao&token=${encodeURIComponent(parsed.data)}`
    : "?tipo=alteracao";
  res.redirect(303, `/confirmar-email${query}`);
});
router.post("/email/confirmar", settings.confirmEmail);
router.get("/preferencias-notificacao", requireAuth, settings.preferences("preferencias"));
router.put("/preferencias-notificacao", requireAuth, validate({body:notificationPreferencesPatchSchema}), settings.preferences("preferencias"));
router.get("/privacidade", requireAuth, settings.preferences("privacidade"));
router.put("/privacidade", requireAuth, validate({ body: privacySchema }), settings.preferences("privacidade"));
router.get("/me/verificacao", requireAuth, identity.identityStatus);
router.post("/verificacao", requireAuth, identityUpload, verifyUploads, identity.submitIdentity);
router.delete("/verificacao", requireAuth, identity.cancelIdentity);
router.get("/me/enderecos", requireAuth, addresses.listAddresses);
router.get("/me/enderecos/:id", requireAuth, validate({params:idParamsSchema}), addresses.getAddress);
router.post("/me/enderecos", requireAuth, validate({body:addressPatchSchema}), addresses.saveAddress);
router.patch("/me/enderecos/:id", requireAuth, validate({params:idParamsSchema,body:addressPatchSchema}), addresses.saveAddress);
router.put("/me/enderecos/:id", requireAuth, validate({params:idParamsSchema,body:addressPatchSchema}), addresses.saveAddress);
router.delete("/me/enderecos/:id", requireAuth, validate({params:idParamsSchema}), addresses.removeAddress);
router.get("/:id/avaliacoes-recebidas", validate({params:idParamsSchema}), listReceivedReviews);
router.get("/:id/avaliacoes-recebidas-locatario", validate({params:idParamsSchema}), listReceivedReviews);
router.get("/:id", validate({params:idParamsSchema}), publicProfile);
export default router;
